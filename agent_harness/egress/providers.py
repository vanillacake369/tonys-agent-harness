"""Render deterministic provider targets from normalized configuration."""

from __future__ import annotations

import json

from agent_harness.domain.config import CAPABILITIES, ROOT, source_digest


def render_skill(name: str, body: str) -> bytes:
    return (
        f'---\nname: {name}\ndescription: "Public engineering workflow: {name}"\n---\n\n'
        f"# {name}\n\n{body}"
    ).encode()


def render_gemini_command(name: str, body: str) -> bytes:
    return (
        f"description = {json.dumps('Public engineering workflow: ' + name)}\n"
        f"prompt = {json.dumps(body)}\n"
    ).encode()


def target_files(config: dict, instruction: bytes) -> dict[str, bytes]:
    marker = f"# Generated by tonys-agent-harness; source digest: {source_digest(config, instruction)}\n"
    files: dict[str, bytes] = {}
    for provider in config["providers"]:
        files[f"{provider}/AGENTS.md"] = instruction
        if provider == "codex":
            files["codex/config.toml"] = (marker + '''default_permissions = "default"\n\n[[hooks.SessionStart]]\n[[hooks.SessionStart.hooks]]\ntype = "command"\ncommand = "python3 ~/.config/agents/governance/task-lifecycle.py start"\ntimeout = 10\n\n[[hooks.PreToolUse]]\nmatcher = "Bash"\n[[hooks.PreToolUse.hooks]]\ntype = "command"\ncommand = "bash ~/.config/agents/governance/pre-tool-gate.sh"\ntimeout = 5\n\n[[hooks.PostToolUse]]\nmatcher = "Bash"\n[[hooks.PostToolUse.hooks]]\ntype = "command"\ncommand = "bash ~/.config/agents/governance/retry-hook.sh post"\ntimeout = 5\n\n[[hooks.Stop]]\n[[hooks.Stop.hooks]]\ntype = "command"\ncommand = "python3 ~/.config/agents/governance/task-lifecycle.py stop"\ntimeout = 10\n\n[permissions.default.filesystem]\n":minimal" = "read"\n"**/.env*" = "deny"\n"**/*credentials*" = "deny"\n"**/secrets/**" = "deny"\n"**/*private*key*" = "deny"\n\n[permissions.default.filesystem.":workspace_roots"]\n"." = "write"\n\n[permissions.agent-reviewer.filesystem]\n":minimal" = "read"\n"**/.env*" = "deny"\n"**/*credentials*" = "deny"\n"**/secrets/**" = "deny"\n"**/*private*key*" = "deny"\n\n[permissions.agent-reviewer.filesystem.":workspace_roots"]\n"." = "read"\n''').encode()
            if config.get("operations", {}).get("profile") == "default-allow-operations-v1":
                files["codex/config.toml"] = files["codex/config.toml"].replace(
                    b'default_permissions = "default"',
                    b'default_permissions = "default-allow-operations-v1"\napproval_policy = "never"',
                ).replace(
                    b'bash ~/.config/agents/governance/pre-tool-gate.sh"',
                    b'~/.config/agents/governance/python3 ~/.config/agents/governance/policy-runtime.py pretool --provider codex --surface cli --profile default-allow-operations-v1 --managed-fragment harness-operation-policy-v1"',
                ) + b'''
[permissions.default-allow-operations-v1.filesystem]
":minimal" = "read"
glob_scan_max_depth = 8
"~/.ssh" = "deny"
"~/.gnupg" = "deny"

[permissions.default-allow-operations-v1.filesystem."~/dev"]
"." = "read"
"**/.env*" = "deny"
"**/*credentials*" = "deny"
"**/secrets/**" = "deny"
"**/*private*key*" = "deny"

[permissions.default-allow-operations-v1.filesystem.":workspace_roots"]
"." = "write"
"**/.env*" = "deny"
"**/*credentials*" = "deny"
"**/secrets/**" = "deny"
"**/*private*key*" = "deny"
"**/.ssh/**" = "deny"
"**/.gnupg/**" = "deny"

[permissions.default-allow-operations-v1.network]
enabled = true
allow_local_binding = true

[permissions.default-allow-operations-v1.network.domains]
"*" = "allow"

[features]
network_proxy = true
'''
        elif provider == "claude":
            payload = {
                "generated": True,
                "sandbox": {"enabled": True, "autoAllowBashIfSandboxed": False},
                "reviewer": {"write": False},
                "hooks": {
                    "SessionStart": [{"hooks": [{"type": "command", "command": "~/.config/agents/governance/python3 ~/.config/agents/governance/policy-runtime.py startup --provider claude --surface cli --managed-fragment harness-policy-preflight-v1; ~/.config/agents/governance/python3 ~/.config/agents/governance/task-lifecycle.py start", "timeout": 10}]}],
                    "PreToolUse": [
                        {"matcher": "mcp__.*", "hooks": [{"type": "command", "command": "bash ~/.config/agents/governance/mcp-hook.sh", "timeout": 5}]},
                        {"matcher": "Bash", "hooks": [{"type": "command", "command": "~/.config/agents/governance/python3 ~/.config/agents/governance/policy-runtime.py pretool --provider claude --surface cli --profile default-allow-operations-v1 --managed-fragment harness-operation-policy-v1", "timeout": 5}]},
                        {"matcher": "Read|Write|Edit|NotebookEdit", "hooks": [{"type": "command", "command": "~/.config/agents/governance/python3 ~/.config/agents/governance/policy-runtime.py pretool --provider claude --surface cli --profile default-allow-operations-v1 --managed-fragment harness-path-invariants-v1", "timeout": 5}]},
                    ],
                    "PostToolUseFailure": [{"matcher": "Bash", "hooks": [{"type": "command", "command": "bash ~/.config/agents/governance/retry-hook.sh failure", "timeout": 5}]}],
                    "Stop": [{"hooks": [{"type": "command", "command": "python3 ~/.config/agents/governance/task-lifecycle.py stop", "timeout": 10}]}],
                },
            }
            files["claude/settings.json"] = (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode()
            files["claude/CLAUDE.md"] = b"@AGENTS.md\n"
            files["claude/agents/independent-reviewer.md"] = b'''---
name: independent-reviewer
description: Read-only independent review of requirements, diffs, tests, and evidence.
tools: Read, Grep, Glob
disallowedTools: Write, Edit, NotebookEdit, Bash
---

Review independently and return structured findings. Never mutate files.
'''
        elif provider == "gemini":
            payload = {
                "context": {"fileName": ["AGENTS.md"]},
                "hooks": {
                    "BeforeAgent": [{"hooks": [{"type": "command", "command": "~/.config/agents/governance/python3 ~/.config/agents/governance/policy-runtime.py startup --provider gemini --surface cli --managed-fragment harness-policy-preflight-v1; ~/.config/agents/governance/python3 ~/.config/agents/governance/task-lifecycle.py start", "timeout": 10000}]}],
                    "BeforeTool": [
                        {"matcher": "run_shell_command|read_file|write_file|replace|replace_in_file", "hooks": [{"type": "command", "command": "~/.config/agents/governance/python3 ~/.config/agents/governance/policy-runtime.py pretool --provider gemini --surface cli --profile default-allow-operations-v1 --managed-fragment harness-operation-policy-v1", "timeout": 5000}]},
                    ],
                    "AfterTool": [{"matcher": "run_shell_command", "hooks": [{"type": "command", "command": "bash ~/.config/agents/governance/retry-hook.sh post", "timeout": 5000}]}],
                    "AfterAgent": [{"hooks": [{"type": "command", "command": "python3 ~/.config/agents/governance/task-lifecycle.py stop", "timeout": 5000}]}],
                },
            }
            files["gemini/settings.json"] = (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode()
        elif provider == "kiro":
            payload = {
                "name": "independent-reviewer", "tools": ["read"], "includeMcpJson": False,
                "permissions": {"fs_write": "deny", "secret_access": "deny"},
            }
            files["kiro/agents/independent-reviewer.json"] = (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode()
            hooks = {"hooks": [{"name": "harness-policy-preflight-v1", "trigger": "AgentSpawn", "command": "~/.config/agents/governance/python3 ~/.config/agents/governance/policy-runtime.py startup --provider kiro --surface cli --managed-fragment harness-policy-preflight-v1; ~/.config/agents/governance/python3 ~/.config/agents/governance/task-lifecycle.py start"}, {"name": "harness-operation-policy-v1", "trigger": "PreToolUse", "matcher": "execute_bash|execute_pwsh", "command": "~/.config/agents/governance/python3 ~/.config/agents/governance/policy-runtime.py pretool --provider kiro --surface cli --profile default-allow-operations-v1 --managed-fragment harness-operation-policy-v1"}, {"name": "harness-path-invariants-v1", "trigger": "PreToolUse", "matcher": "fs_read|fs_write|fs_append|str_replace|delete_file", "command": "~/.config/agents/governance/python3 ~/.config/agents/governance/policy-runtime.py pretool --provider kiro --surface cli --profile default-allow-operations-v1 --managed-fragment harness-path-invariants-v1"}, {"trigger": "PostToolUse", "matcher": "execute_bash|fs_write", "command": "bash ~/.config/agents/governance/retry-hook.sh post"}, {"trigger": "Stop", "command": "bash ~/.config/agents/governance/kiro-stop.sh"}]}
            files["kiro/hooks/engineering-governance.json"] = (json.dumps(hooks, indent=2, sort_keys=True) + "\n").encode()
    if "codex/config.toml" in files:
        files["codex/config.toml"] = files["codex/config.toml"].replace(
            b"python3 ~/.config/agents/governance/task-lifecycle.py start",
            b"~/.config/agents/governance/python3 ~/.config/agents/governance/policy-runtime.py startup --provider codex --surface cli --managed-fragment harness-policy-preflight-v1; ~/.config/agents/governance/python3 ~/.config/agents/governance/task-lifecycle.py start",
        )
        files["codex/config.toml"] = files["codex/config.toml"].replace(
            b'task-lifecycle.py stop"', b'task-lifecycle.py stop >/dev/null"'
        )
    retry_max = str(config.get("verification", {}).get("retry_max", 3))
    for name in ("codex/config.toml", "claude/settings.json", "gemini/settings.json", "kiro/hooks/engineering-governance.json"):
        if name in files:
            files[name] = files[name].replace(b"retry-hook.sh post", f"retry-hook.sh post {retry_max}".encode())
            files[name] = files[name].replace(b"retry-hook.sh failure", f"retry-hook.sh failure {retry_max}".encode())
    capabilities = {
        name: CAPABILITIES[name] | {
            "operation_policy": {
                "profile": "default-allow-operations-v1",
                "hook_porter": "implemented",
            },
        }
        for name in config["providers"]
    }
    files["capabilities.json"] = (json.dumps(capabilities, indent=2, sort_keys=True) + "\n").encode()
    skill_sources = sorted(path for path in (ROOT / "assets/skills").rglob("*") if path.is_file())
    command_sources = sorted((ROOT / "assets/commands").glob("cmd-*.md"))
    for provider in config["providers"]:
        for source in skill_sources:
            relative = source.relative_to(ROOT / "assets/skills")
            if provider == "gemini":
                if relative.name == "SKILL.md":
                    files[f"gemini/commands/{relative.parent.name}.toml"] = render_gemini_command(
                        relative.parent.name, source.read_text()
                    )
            else:
                files[f"{provider}/skills/{relative}"] = source.read_bytes()
        for source in command_sources:
            if provider == "codex":
                files[f"codex/skills/workflow-{source.stem}/SKILL.md"] = render_skill(
                    f"workflow-{source.stem}", source.read_text()
                )
            elif provider in ("claude", "kiro"):
                files[f"{provider}/skills/{source.stem}/SKILL.md"] = render_skill(
                    source.stem, source.read_text()
                )
            elif provider == "gemini":
                files[f"gemini/commands/{source.stem}.toml"] = render_gemini_command(
                    source.stem, source.read_text()
                )
    for source in sorted(path for path in (ROOT / "runtime").rglob("*")
                         if path.is_file() and "__pycache__" not in path.parts and path.suffix in {".sh", ".py"}):
        files[f"runtime/{source.relative_to(ROOT / 'runtime')}"] = source.read_bytes()
    files["install-map.json"] = (json.dumps({
        "runtime": "~/.config/agents",
        "providers": {name: f"~/.{name}" for name in config["providers"]},
        "activation": "harness-home-manager-owned-links",
    }, indent=2, sort_keys=True) + "\n").encode()
    return files
